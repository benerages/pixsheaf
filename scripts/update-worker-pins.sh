#!/usr/bin/env bash
# Resolves the pins of the worker image (ADR 0018) and writes them in place:
#   1. the current digest of cgr.dev/chainguard/wolfi-base:latest,
#   2. the commit of each source tag (ARG *_VERSION / *_COMMIT pairs),
#   3. deploy/docker/wolfi/build.lock from deploy/docker/wolfi/build.packages.
# Review the result with `git diff` before committing.
# Requires Docker (with buildx), git, and internet access.
set -Eeuo pipefail
trap 'echo "update-worker-pins: failed at line $LINENO" >&2' ERR
cd "$(dirname "$0")/.."

dockerfile=deploy/docker/worker.Dockerfile
packages=deploy/docker/wolfi/build.packages
lock=deploy/docker/wolfi/build.lock

# 1. Base image digest.
# awk reads all input: exiting early would SIGPIPE docker and, with
# pipefail, end the script without a message.
digest=$(docker buildx imagetools inspect cgr.dev/chainguard/wolfi-base:latest |
  awk '/^Digest:/ && !found { print $2; found = 1 }')
[[ $digest =~ ^sha256:[0-9a-f]{64}$ ]] || { echo "could not resolve wolfi-base digest" >&2; exit 1; }
sed -i "s#^ARG WOLFI_IMAGE=.*#ARG WOLFI_IMAGE=cgr.dev/chainguard/wolfi-base:latest@${digest}#" "$dockerfile"
echo "wolfi-base: $digest"

# 2. Source commits. Each pair is preceded by a Renovate comment naming
#    the GitHub repository.
resolve() {
  local var=$1 repo tag sha
  repo=$(grep -B1 "^ARG ${var}_VERSION=" "$dockerfile" | sed -n 's/.*depName=\([^ ]*\).*/\1/p')
  tag=$(sed -n "s/^ARG ${var}_VERSION=//p" "$dockerfile")
  [[ -n $repo && -n $tag ]] || { echo "${var}: repository or tag missing in $dockerfile" >&2; return 1; }
  # Annotated tags: the peeled ref (^{}) is the commit.
  sha=$(git ls-remote "https://github.com/${repo}.git" "refs/tags/${tag}^{}" | awk '{ print $1 }')
  [[ -n $sha ]] || sha=$(git ls-remote "https://github.com/${repo}.git" "refs/tags/${tag}" | awk '{ print $1 }')
  [[ $sha =~ ^[0-9a-f]{40}$ ]] || { echo "${var}: tag ${tag} not found in ${repo}" >&2; return 1; }
  sed -i "s/^ARG ${var}_COMMIT=.*/ARG ${var}_COMMIT=${sha}/" "$dockerfile"
  echo "${repo} ${tag}: ${sha}"
}
for var in QUANTIZR CGIF LIBDE265 LIBHEIF LIBVIPS; do
  resolve "$var"
done

# 3. Package lock: everything apk installs on top of the pinned base image.
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
grep -v '^#' "$packages" | sed '/^$/d' |
  docker run --rm -i "cgr.dev/chainguard/wolfi-base:latest@${digest}" sh -euc '
    apk info -v | sort > /tmp/base
    apk add --no-cache $(cat) > /dev/null
    apk info -v | sort > /tmp/all
    comm -13 /tmp/base /tmp/all | sed "s/-\([^-]*-r[0-9]*\)\$/=\1/"
  ' >"$tmp"
[[ -s $tmp ]] || { echo "package resolution produced no output" >&2; exit 1; }
{
  echo "# Generated by scripts/update-worker-pins.sh. Do not edit by hand."
  echo "# Base: cgr.dev/chainguard/wolfi-base:latest@${digest}"
  cat "$tmp"
} >"$lock"
echo "build.lock: $(grep -vc '^#' "$lock") packages"

echo
git --no-pager diff --stat -- "$dockerfile" "$lock"
